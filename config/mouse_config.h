#ifndef __MOUSE_CONFIG_H
#define __MOUSE_CONFIG_H


/*********************************************************************************************************
  常量宏定义 -- 迷宫类型
*********************************************************************************************************/
#define MAZETYPE        16                                              /*  8: 四分之一迷宫；16: 全迷宫 */


/*********************************************************************************************************
  常量宏定义 -- 设定四分之一迷宫的终点坐标
*********************************************************************************************************/
#if MAZETYPE == 8
#define XDST0           6
#define XDST1           6
#define YDST0           6
#define YDST1           6
#endif


/*********************************************************************************************************
  常量宏定义 -- 设定全迷宫的终点坐标
  注意: 运行期 main() 会把 X 目标覆盖为 8/7（见 TUNE_GOAL_X0/X1），Y 仍取 6/6；
    goalwall() 内部按 7/8 的墙处理。三处历史值不一致，改动前务必实车确认。
*********************************************************************************************************/
#if MAZETYPE == 16
#define XDST0           6
#define XDST1           6
#define YDST0           6
#define YDST1           6
#endif


/*********************************************************************************************************
  常量宏定义 -- 设置迷宫搜索法则
  可以使用的法则:
  RIGHTMETHOD           -- 右手法则
  LEFTMETHOD            -- 左手法则
  CENTRALMETHOD         -- 中心法则
  FRONTRIGHTMETHOD      -- 中右法则
  FRONTLEFTMETHOD       -- 中左法则
  CORNERMETHOD          -- 向角法则
*********************************************************************************************************/
#define SEARCHMETHOD  CENTRALMETHOD                         /*  设置迷宫搜索法则为中心*/


/*********************************************************************************************************
  常量宏定义--电机运行速度（单位：每 1 ms 编码器脉冲数）
*********************************************************************************************************/
#define SEARCHSPEED    140                                  /*  搜索迷宫时的最大速度        */
#define MINSPEED       10                                   /*  减速运行时的最小速度        */


/*********************************************************************************************************
  常量宏定义--前进一个迷宫格需要走的编码器脉冲数
*********************************************************************************************************/
#define ONEBLOCK        51600                               /*  电机走一格迷宫所需脉冲数    */
#define ONEBLOCK_45     36410                               /*  斜向走一格（对角线）脉冲数  */


/*********************************************************************************************************
  重点调车参数集中在 tuning.h（本文件末尾自动包含）
*********************************************************************************************************/
#include "tuning.h"

#endif
